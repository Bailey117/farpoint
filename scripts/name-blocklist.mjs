// Regenerates src/data/nameBlocklist.ts: every name the generator can make
// that is also a real word or proper noun, so it is never used.
//
//   node scripts/name-blocklist.mjs path/to/words.txt
//
// words.txt is one word per line, e.g. https://github.com/dwyl/english-words
// (words.txt, which includes names of peoples and places). Re-run after
// changing NAME_STYLES. The pleasant() rules mirror isPleasant() in
// src/game/setting.ts.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync('src/data/setting.ts', 'utf8');
const block = src.slice(src.indexOf('export const NAME_STYLES = {'), src.indexOf('} as const satisfies Record<string, NameStyle>'));
const arr = (s) => JSON.parse(s.replace(/'/g, '"'));
const styles = {};
for (const m of block.matchAll(/^\s+(\w+): \{ first: (\[[^\]]*\]), onsets: (\[[^\]]*\]), vowels: (\[[^\]]*\]), codas: (\[[^\]]*\])/gm)) {
  styles[m[1]] = { first: arr(m[2]), onsets: arr(m[3]), vowels: arr(m[4]), codas: arr(m[5]) };
}
if (Object.keys(styles).length === 0) throw new Error('No name styles found in src/data/setting.ts');

const pleasant = (n) =>
  !(n.length < 5 || n.length > 10 || /[^aeiouy]{4}/.test(n) || /[aeiou]{3}/.test(n) || /aa|ii|uu|yy/.test(n) || /(.)\1\1/.test(n) || /(..).?\1/.test(n) || !/[aeiouy]/.test(n));

const words = new Set(readFileSync(process.argv[2], 'utf8').split(/\r?\n/).map((w) => w.trim().toLowerCase()));
const hits = new Set();
for (const [id, st] of Object.entries(styles)) {
  const firsts = st.first.flatMap((o) => (/^[aeiouy]/.test(o) ? [o] : st.vowels.map((v) => o + v)));
  const mids = st.onsets.flatMap((o) => st.vowels.map((v) => o + v));
  const stems = [];
  for (const a of firsts) {
    stems.push(a);
    for (const b of mids) {
      if (b === a) continue;
      stems.push(a + b);
      for (const c of mids) if (c !== b) stems.push(a + b + c);
    }
  }
  const names = new Set(stems.flatMap((s) => st.codas.map((c) => s + c)).filter(pleasant));
  const own = [...names].filter((n) => words.has(n));
  for (const n of own) hits.add(n);
  console.log(`${id}: ${names.size} possible names, ${own.length} blocked`);
}

const list = [...hits].sort();
const lines = [];
for (let i = 0; i < list.length; i += 12) lines.push(`  '${list.slice(i, i + 12).join(' ')}',`);
writeFileSync(
  'src/data/nameBlocklist.ts',
  `/**
 * Generated by scripts/name-blocklist.mjs: names the generator could make
 * that are real words or names (of people, peoples or places). Never used.
 */

export const NAME_BLOCKLIST: ReadonlySet<string> = new Set(
  [
${lines.join('\n')}
  ]
    .join(' ')
    .split(' '),
);
`,
);
console.log(`Wrote ${list.length} names to src/data/nameBlocklist.ts`);
